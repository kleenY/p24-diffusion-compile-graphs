"""Tab.II of the paper (S5 P0-4): policy versus baselines, S3 part only.

    python -m p24.paper.tab_policy [--out paper/paper/tables/tab2_policy.tex] [--registry-out paper/paper/registry_extra/tab2_policy.csv]

Blocks (all numbers are \\N... macros; the .tex holds no number):
  1. total service time / B0, W1-W3, N=10^4, disk-cache tier (results/S3/sim_eval/figs_v2_annotated/main_figure_table.csv): Ours, B1(dagger), B7.
  2. H4a/b/c statistic and verdict (results/S3/sim_eval/h4_verdict.json, primary N=10^4).
  3. ablation, mean total service time over the 10 evaluation seeds (results/S3/sim_eval/ablation_raw.csv): W2 and W5, N=10^4.
  4. tight memory budget, W2/W3, N=10^4 (results/S3/sim_eval/budget_raw.csv).
  5. simulator validation error of the S3 3.4 table (results/S3/real_validation/error_table.csv).
  6. PLACEHOLDER rows for block C (simulator validation v2) and the recipe-R serving row.  Their macros end in TBD, are NOT registered
     (no value yet) and are defined in the .tex by \\providecommand so that the document compiles; p24.paper.check treats names
     ending in TBD as placeholders (warning only).  Replace them by registered macros after the block-C SHA16 is logged.
GenEval row (S4, frozen, macros already registered) is not part of the P0 S3 scope and is added in the formal S5 phase.
Existing macros of registry.py (NTab..TenK, NHfour.., NReal..) are reused, only missing ones are registered in registry_extra/tab2_policy.csv.
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import List, Sequence

from p24.paper import style as st
from p24.paper._tabutil import registry_csv_text, write_text
from p24.paper.registry import Reg

MFT = "results/S3/sim_eval/figs_v2_annotated/main_figure_table.csv"
MFT_SCRIPT = "code/p24/reproduce_main_figure.py"
H4 = "results/S3/sim_eval/h4_verdict.json"
H4_SCRIPT = "code/scripts/h4_verdict_S3.py"
AB = "results/S3/sim_eval/ablation_raw.csv"
BU = "results/S3/sim_eval/budget_raw.csv"
SIM_SCRIPT = "code/scripts/sim_eval_S3.py"
ET = "results/S3/real_validation/error_table.csv"
RV_SCRIPT = "code/scripts/compare_S3_4.py"

PLACEHOLDERS = {                      # macro -> text shown until block C is frozen (NOT registered)
    "NTabCSimErrTBD": "TBD",
    "NTabCSimVerdictTBD": "TBD",
    "NTabRServeTBD": "TBD",
    "NTabRServeCITBD": "TBD",
}

WL = [("W1", "Wone"), ("W2", "Wtwo"), ("W3", "Wthree")]
POL = [("Ours", "Ours"), ("B1", "BOne"), ("B7", "BSeven")]
EXISTING = {"NTabWtwoOursTenK", "NTabWtwoBOneTenK", "NTabWtwoBSevenTenK", "NTabWoneOursTenK"}      # already in registry.py
ABL = [("Ours (full)", "Ours", "Ours"), ("v1 specification", "Ours:v1_spec", "VOne"), ("three tiers", "Ours:three_tiers", "ThreeTiers"),
       ("LRU eviction (B5)", "B5", "Lru"), ("no prior", "Ours:no_prior", "NoPrior"), ("B0 (eager)", "B0", "BZero")]
ABL_WL = [("W2", "Wtwo"), ("W5", "Wfive")]
TIGHT_POL = [("B0", "BZero"), ("Ours", "Ours"), ("B1", "BOne")]
TIGHT_WL = [("W2", "Wtwo"), ("W3", "Wthree")]


def registry() -> List[Reg]:
    regs: List[Reg] = []
    for w, wm in WL:                                                           # block 1
        for p, pm in POL:
            name = f"NTab{wm}{pm}TenK"
            if name not in EXISTING:
                regs.append(Reg(name, MFT, f"mean?workload={w}&cold=disk&variant={p}&N=10000", ".3f", "Tab.II", MFT_SCRIPT))
    for k, sec in (("A", "H4a_W2"), ("B", "H4b_W3"), ("C", "H4c_W1")):         # block 2: verdict strings (statistics exist already)
        regs.append(Reg(f"NHfour{k}VerdictTenK", H4, f"per_N.10000.{sec}.verdict", "s", "Tab.II", H4_SCRIPT))
    for label, var, vm in ABL:                                                 # block 3
        for w, wm in ABL_WL:
            regs.append(Reg(f"NTabAbl{vm}{wm}Sec", AB, f"service_s?variant={var}&workload={w}&N=10000#mean", ".0f", "Tab.II", SIM_SCRIPT))
    regs.append(Reg("NTabTightBudgetGB", BU, "budget_mb?budget=tight#mean", "/1024:.1f", "Tab.II", SIM_SCRIPT))   # block 4
    for w, wm in TIGHT_WL:
        for p, pm in TIGHT_POL:
            regs.append(Reg(f"NTabTight{pm}{wm}Sec", BU, f"service_s?budget=tight&variant={p}&workload={w}&N=10000#mean", ".0f",
                            "Tab.II", SIM_SCRIPT))
    regs.append(Reg("NRealErrBOneWthreePct", ET, "error?stream=W3_N300_seed100_B&policy=B1&cache_mode=warm", "*100:.1f", "Tab.II", RV_SCRIPT))
    return regs


def _m(name: str) -> str:
    return "\\" + name


def render() -> str:
    L = ["% AUTO-GENERATED by `python -m p24.paper.tab_policy` -- do not edit by hand.  Every number is a \\N... macro (numbers.tex);",
         "% macros ending in TBD are placeholders for block C / recipe R (defined here, not registered).",
         ] + [f"\\providecommand{{\\{k}}}{{\\textbf{{{v}}}}}" for k, v in PLACEHOLDERS.items()] + [
         "\\begin{table}[t]",
         "\\caption{Policy versus baselines from the request-level simulator on the evaluation seeds, disk-cache tier. "
         "The dagger marks a baseline whose simulated totals were not confirmed by real replays. Ablation and budget rows give the mean "
         "total service time in seconds.}",
         "\\label{tab:policy}",
         "\\centering\\footnotesize",
         "\\setlength{\\tabcolsep}{2.5pt}",
         "\\begin{tabular}{@{}lrrr@{}}",
         "\\toprule",
         "\\multicolumn{4}{@{}l}{\\emph{Total time / B0, $N{=}10^4$}} \\\\",
         "Workload & Ours & B1$^\\dagger$ & B7 \\\\",
         "\\midrule"]
    for w, wm in WL:
        L.append(f"{w} & " + " & ".join(_m(f"NTab{wm}{pm}TenK") for _, pm in POL) + " \\\\")
    L += ["\\midrule",
          "\\multicolumn{4}{@{}l}{\\emph{Hypotheses (primary cell)}} \\\\",
          "H4a (W2), vs.\\ best online & $+$" + _m("NHfourAGapPctTenK") + "\\% & [" + _m("NHfourABootLoPctTenK") + ", "
          + _m("NHfourABootHiPctTenK") + "] & " + _m("NHfourAVerdictTenK") + " \\\\",
          "H4b (W3), Ours / B0 & " + _m("NHfourBRatioTenK") + " & & " + _m("NHfourBVerdictTenK") + " \\\\",
          "H4c (W1), Ours / B1 & " + _m("NHfourCRatioTenK") + " & & " + _m("NHfourCVerdictTenK") + " \\\\",
          "\\midrule",
          "\\multicolumn{4}{@{}l}{\\emph{Ablation (mean total time, s)}} \\\\",
          "Variant & W2 & W5 & \\\\"]
    for label, _var, vm in ABL:
        L.append(f"\\quad {label} & " + " & ".join(_m(f"NTabAbl{vm}{wm}Sec") for _, wm in ABL_WL) + " & \\\\")
    L += ["\\midrule",
          "\\multicolumn{4}{@{}l}{\\emph{Tight budget (" + _m("NTabTightBudgetGB") + "{} GB), total time (s)}} \\\\",
          "Workload & B0 & Ours & B1$^\\dagger$ \\\\"]
    for w, wm in TIGHT_WL:
        L.append(f"{w} & " + " & ".join(_m(f"NTabTight{pm}{wm}Sec") for _, pm in TIGHT_POL) + " \\\\")
    L += ["\\midrule",
          "\\multicolumn{4}{@{}l}{\\emph{Simulator validation, real replays (error, \\%)}} \\\\",
          "Policy & W2 & W3 & \\\\",
          "\\quad Ours & " + _m("NRealErrOursWtwoPct") + " & " + _m("NRealErrOursWthreePct") + " & \\\\",
          "\\quad B1$^\\dagger$ & " + _m("NRealErrBOneWtwoPct") + " & " + _m("NRealErrBOneWthreePct") + " & \\\\",
          "\\quad worst of " + _m("NRealJudged") + "{} runs & " + _m("NRealMaxErrPct") + " & & \\\\",
          "\\midrule",
          "\\multicolumn{4}{@{}l}{\\emph{Pending (block C, recipe R)}} \\\\",
          "\\quad Validation v2, error / verdict & " + _m("NTabCSimErrTBD") + " & " + _m("NTabCSimVerdictTBD") + " & \\\\",
          "\\quad Recipe R, serving & " + _m("NTabRServeTBD") + " & " + _m("NTabRServeCITBD") + " & \\\\",
          "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)


def main(argv: Sequence[str] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(st.TAB_DIR / "tab2_policy.tex"))
    ap.add_argument("--registry-out", default=str(st.ROOT / "paper/paper/registry_extra/tab2_policy.csv"))
    a = ap.parse_args(argv)
    write_text(Path(a.registry_out), registry_csv_text(registry()))
    write_text(Path(a.out), render())
    print(f"wrote {a.out} and {a.registry_out} ({len(registry())} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
