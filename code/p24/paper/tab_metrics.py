"""Tab.I of the paper (S5 P0-4): the five metrics required by the course supervisor x representative shapes.

    python -m p24.paper.tab_metrics [--out paper/paper/tables/tab1_metrics.tex] [--registry-out paper/paper/registry_extra/tab1_metrics.csv]

Metrics: compile time, first-request latency, steady-state latency, graph memory, break-even count (graph / compile-disk /
compile-empty, with CI).  Sources: results/S2/cost_table/merged/cost_table.csv (CT) and results/S2/breakeven/breakeven.csv (BE).
EVERY number in the .tex is a \\N... macro; the macro list (name -> source, selector, format) is generated from SHAPES x ROWS below and
written to registry_extra/tab1_metrics.csv, so `python -m p24.paper.build` fills numbers.tex.  The .tex itself contains no number,
hence it is byte-stable.  Block-A supplement: append shape specs to BLOCK_A_SHAPES (same tuple layout as SHAPES) after the
block-A outputs are frozen and their SHA16 logged; the columns appear automatically (single-column width fits 3-4 columns).
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import List, Sequence, Tuple

from p24.paper import style as st
from p24.paper._tabutil import registry_csv_text, write_text
from p24.paper.registry import Reg

CT = "results/S2/cost_table/merged/cost_table.csv"
BE = "results/S2/breakeven/breakeven.csv"
CT_SCRIPT = "code/scripts/build_cost_table.py"
BE_SCRIPT = "code/p24/sim/breakeven.py"
# (macro tag, H, W, B, cfg, header)
Shape = Tuple[str, int, int, int, int, str]
SHAPES: List[Shape] = [
    ("FiveBOne", 512, 512, 1, 0, "512$^2$, B1"),
    ("SevenBOne", 768, 768, 1, 0, "768$^2$, B1"),
    ("FiveBFourCfg", 512, 512, 4, 1, "512$^2$, B4+CFG"),
]
BLOCK_A_SHAPES: List[Shape] = []          # interface for the block-A supplement (empty until frozen)

# (group title, [(row label, kind, stem, source, column, arm_or_tier, fmt, ci)])  kind: ct (filter arm=) | be (filter tier=)
ROWS = [
    ("Steady-state latency (ms)", [
        ("E0 (eager)", "ct", "SteadyEZero", "steady_ms", "E0", ".1f", False),
        ("C1+G1", "ct", "SteadyCOneGOne", "steady_ms", "C1+G1", ".1f", False)]),
    ("Compile time (s)", [
        ("empty cache", "be", "CompileEmpty", "cc_s", "cold_empty", ".1f", False),
        ("disk cache", "be", "CompileDisk", "cc_s", "cold_diskcache", ".1f", False)]),
    ("First-request latency (s)", [
        ("E0 (eager)", "ct", "FirstEZero", "first_req_s__cold_empty", "E0", ".1f", False),
        ("C1+G1, empty", "ct", "FirstCOneGOneEmpty", "first_req_s__cold_empty", "C1+G1", ".1f", False),
        ("C1+G1, disk", "ct", "FirstCOneGOneDisk", "first_req_s__cold_diskcache", "C1+G1", ".1f", False)]),
    ("Graph memory (MB)", [
        ("G1 pool", "ct", "PoolGOne", "capture_pool_mb", "G1", "d", False),
        ("C1+G1 pool", "ct", "PoolCOneGOne", "capture_pool_mb", "C1+G1", "d", False)]),
    ("Break-even count (requests)", [
        ("graph (G1)", "be", "BreakGraph", "n_capture", "cold_diskcache", ".0f", True),
        ("compile, disk", "be", "BreakCompileDisk", "n_compile", "cold_diskcache", ".0f", True),
        ("compile, empty", "be", "BreakCompileEmpty", "n_compile", "cold_empty", ".0f", True)]),
]
# be-rows whose CI columns are <col>_lo / <col>_hi (n_capture_lo, n_compile_lo, ...)


def all_shapes() -> List[Shape]:
    return list(SHAPES) + list(BLOCK_A_SHAPES)


def _selector(col: str, kind: str, key: str, s: Shape) -> str:
    _, h, w, b, cfg, _ = s
    shape = f"H={h}&W={w}&B={b}&cfg={cfg}"
    return f"{col}?arm={key}&{shape}" if kind == "ct" else f"{col}?{shape}&tier={key}"


def macro_name(stem: str, tag: str, suffix: str = "") -> str:
    return f"NTabI{stem}{suffix}{tag}"


def registry() -> List[Reg]:
    regs: List[Reg] = []
    for s in all_shapes():
        for _, rows in ROWS:
            for _label, kind, stem, col, key, fmt, ci in rows:
                src, scr = (CT, CT_SCRIPT) if kind == "ct" else (BE, BE_SCRIPT)
                regs.append(Reg(macro_name(stem, s[0]), src, _selector(col, kind, key, s), fmt, "Tab.I", scr))
                if ci:
                    for suf, sfx in (("Lo", "_lo"), ("Hi", "_hi")):
                        regs.append(Reg(macro_name(stem, s[0], suf), src, _selector(col + sfx, kind, key, s), fmt, "Tab.I", scr))
    return regs


def render() -> str:
    shapes = all_shapes()
    n = len(shapes)
    L = ["% AUTO-GENERATED by `python -m p24.paper.tab_metrics` -- do not edit by hand.  Every number is a \\N... macro (numbers.tex).",
         "\\begin{table}[t]",
         "\\caption{Cost metrics per request shape on the main platform (SD1.5 + LCM-LoRA, fp16, four steps). "
         "B is the batch size, CFG the guided variant. Break-even counts are the numbers of requests that repay the "
         "one-time cost; brackets are confidence intervals (process bootstrap).}",
         "\\label{tab:metrics}",
         "\\centering\\footnotesize",
         "\\setlength{\\tabcolsep}{2pt}",
         "\\begin{tabular}{@{}l" + "r" * n + "@{}}",
         "\\toprule",
         "Metric & " + " & ".join(s[5] for s in shapes) + " \\\\",
         "\\midrule"]
    for gi, (title, rows) in enumerate(ROWS):
        if gi:
            L.append("\\addlinespace[1pt]")
        L.append(f"\\multicolumn{{{n + 1}}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\")
        for label, kind, stem, col, key, fmt, ci in rows:
            L.append(f"\\quad {label} & " + " & ".join("\\" + macro_name(stem, s[0]) for s in shapes) + " \\\\")
            if ci:               # confidence interval on its own (smaller) row: keeps the table inside one column
                L.append("& " + " & ".join("{\\scriptsize [\\" + macro_name(stem, s[0], "Lo") + ", \\" + macro_name(stem, s[0], "Hi") + "]}"
                                         for s in shapes) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)


def main(argv: Sequence[str] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(st.TAB_DIR / "tab1_metrics.tex"))
    ap.add_argument("--registry-out", default=str(st.ROOT / "paper/paper/registry_extra/tab1_metrics.csv"))
    a = ap.parse_args(argv)
    write_text(Path(a.registry_out), registry_csv_text(registry()))
    write_text(Path(a.out), render())
    print(f"wrote {a.out} and {a.registry_out} ({len(registry())} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
